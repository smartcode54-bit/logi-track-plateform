// FileOwner expands §5's precedence: generated outputs, named exceptions, then
// package allocations. A physical path resolves to one owner, never two lists.
func FileOwner(path string) string {
	path = filepath.ToSlash(path)
	if strings.HasPrefix(path, "logitrack-api/") {
		p := strings.TrimPrefix(path, "logitrack-api/")
		if strings.HasSuffix(p, ".go") && !strings.HasSuffix(p, "_test.go") {
			if data, err := os.ReadFile(filepath.Join(repositoryRoot(), path)); err == nil && strings.Contains(string(data), "Code generated by sqlc.") {
				return "P1.0"
			}
		}
		// PSAP10 review items 2/9: named P1.2 handoff exception, derived-read matrix cells only.
		if p == "internal/iam/matrix.go" || p == "internal/iam/support_matrix_test.go" {
			return "P1.0"
		}
		for _, name := range []string{"principal", "rls", "http"} {
			if p == "internal/authz/"+name+".go" || p == "internal/authz/"+name+"_test.go" {
				return "P1.1"
			}
		}
		for _, name := range []string{"principal", "principal_test", "principal_integration_test"} {
			if p == "internal/platform/db/"+name+".go" {
				return "P1.1"
			}
		}
		for _, name := range []string{"support_visits", "support_visits_integration_test"} {
			if p == "internal/platform/db/"+name+".go" {
				return "P1.2"
			}
		}
		for _, prefix := range []string{"internal/platform/httpx/", "internal/platform/ingress/", "internal/platform/db/", "internal/authz/", "internal/app/", "cmd/", "tools/analyzers/", "internal/billing/", "internal/broadcasts/", "internal/chats/", "internal/expenses/", "internal/hr/", "internal/hubs/", "internal/linenotify/", "internal/operations/", "internal/parties/", "internal/webcfg/"} {
			if strings.HasPrefix(p, prefix) {
				return "P1.0"
			}
		}
		if p == "deploy/Dockerfile" || p == "Makefile" || p == "sqlc.yaml" || p == "api/routes.txt" || p == "api/support-policies.json" || p == "api/support-discovery.json" {
			return "P1.0"
		}
		for _, name := range []string{"authorize.go", "rbac.go", "authorize_test.go", "rbac_integration_test.go"} {
			if p == "internal/iam/"+name {
				return "P1.1"
			}
		}
		for owner, prefixes := range map[string][]string{
			"P1.1": {"internal/auth/", "internal/scheduler/"},
			"P1.2": {"internal/iam/", "internal/security/", "internal/notify/", "internal/mobileapp/", "internal/forms/", "migrations/0027_"},
			"P1.3": {"internal/dashboard/", "internal/drivers/", "internal/fleet/", "internal/maintenance/"},
			"P1.4": {"internal/storage/", "internal/sse/", "internal/jobs/", "internal/platform/realtime/", "internal/platform/cache/"},
			"P1.8": {"internal/supportacceptance/"},
		} {
			for _, prefix := range prefixes {
				if strings.HasPrefix(p, prefix) {
					return owner
				}
			}
		}
	}
	for _, p := range []string{".github/workflows/go-ci.yml", ".github/workflows/ci.yml", "logitrack-web/package.json", "logitrack-web/eslint.config.mjs", "logitrack-web/scripts/check-masked-money.mjs", "logitrack-web/scripts/check-masked-money.test.mjs", "logitrack-web/scripts/support-header-baseline.json", "shared-docs/schemas/capabilities.ts", "shared-docs/schemas/supportAccess.ts"} {
		if path == p {
			return "P1.0"
		}
	}
	return ""
}
func checkOwnership(root string) error {
	for _, args := range [][]string{{"diff", "--name-only", "HEAD"}, {"ls-files", "--others", "--exclude-standard"}} {
		cmd := exec.Command("git", args...)
		cmd.Dir = filepath.Join(root, "..")
		output, err := cmd.Output()
		if err != nil {
			return err
		}
		for _, path := range strings.Fields(string(output)) {
			owner := FileOwner(path)
			if owner != "P1.0" {
				return fmt.Errorf("changed physical file %s belongs to %q, not P1.0", path, owner)
			}
		}
	}
	return nil
}

func repositoryRoot() string {
	dir, _ := os.Getwd()
	for {
		if _, err := os.Stat(filepath.Join(dir, ".git")); err == nil {
			return dir
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return ""
		}
		dir = parent
	}
}
